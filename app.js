function updateStats() {
  const today = new Date().toDateString();
  const todayReports = state.reports.filter((report) => {
    const sameDay = new Date(report.createdAt).toDateString() === today;
    const sameSchool = report.schoolId ? report.schoolId === state.selectedSchoolId : true;
    return sameDay && sameSchool;
  });

  if (elements.todayCount) elements.todayCount.textContent = String(todayReports.length);
  if (elements.selectedCount) elements.selectedCount.textContent = String(state.selectedStudents.length);

  const lastReport = state.reports.find((report) => (report.schoolId || state.selectedSchoolId) === state.selectedSchoolId);
  if (elements.lastSavedLabel) elements.lastSavedLabel.textContent = lastReport ? formatDateTime(lastReport.createdAt) : '--';
}

