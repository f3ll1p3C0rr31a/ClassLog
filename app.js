function buildStudentRoster(groups) {
  const names = groups.flatMap((group) => group.students);
  const firstNameCounts = names.reduce((counts, fullName) => {
    const firstName = normalizeKey(fullName.split(/\s+/)[0]);
    counts[firstName] = (counts[firstName] || 0) + 1;
    return counts;
  }, {});

  return groups.flatMap((group) => group.students.map((fullName) => {
    const parts = fullName.split(/\s+/);
    const firstName = parts[0];
    const lastName = parts[parts.length - 1];
    const displayName = firstNameCounts[normalizeKey(firstName)] > 1 ? `${firstName} ${lastName}` : firstName;

    return {
      fullName,
      displayName: titleCase(displayName),
      firstName: titleCase(firstName),
      classKey: group.key,
      classLabel: group.label,
    };
  }));
}

function getStudentRoster() {
  return buildStudentRoster(getCurrentClassGroups());
}

function getStudentMap() {
  return new Map(getStudentRoster().map((student) => [student.fullName, student]));
}

function normalizeDraftSchoolSelection(nextSchoolId) {
  const validSchool = getSchools().some((school) => school.id === nextSchoolId);
  return validSchool ? nextSchoolId : getSchools()[0]?.id || 'fatima';
}

function rebuildSchoolDependentState() {
  state.selectedSchoolId = normalizeDraftSchoolSelection(state.selectedSchoolId);

  const classes = getCurrentClassGroups();
  const classKeys = new Set(classes.map((group) => group.key));
  if (!classKeys.has(state.selectedClass)) {
    state.selectedClass = classes[0]?.key || '';
  }

  const studentsByName = getStudentMap();
  state.selectedStudents = state.selectedStudents.filter((fullName) => studentsByName.has(fullName));

  const occurrenceTypes = getOccurrenceTypes();
  if (!occurrenceTypes.includes(state.selectedOccurrence)) {
    state.selectedOccurrence = occurrenceTypes[0] || 'Outra';
    if (state.selectedOccurrence !== 'Outra') {
      state.customOccurrence = '';
    }
  }
}

async function apiRequest(pathname, options = {}) {
  const response = await fetch(pathname, {
    credentials: 'include',
    headers: {
      'Content-Type': 'application/json',
      ...(options.headers || {}),
    },
    ...options,
  });

  const contentType = response.headers.get('content-type') || '';
  const body = contentType.includes('application/json') ? await response.json() : null;

  if (!response.ok) {
    const error = new Error(body?.error || 'request_failed');
    error.status = response.status;
    error.body = body;
    throw error;
  }

  return body;
}

async function loadAuthUser() {
  try {
    const response = await apiRequest('/api/auth/me', { method: 'GET' });
    state.authUser = response.user;
    return response.user;
  } catch {
    state.authUser = null;
    return null;
  }
}

async function loadContext() {
  const response = await apiRequest('/api/context', { method: 'GET' });
  state.settings = response.settings || { schools: [], holidays: [] };

  if (!state.manualSchoolSelection) {
    state.selectedSchoolId = response.activeSchoolId || state.selectedSchoolId;
  }

  rebuildSchoolDependentState();
}

async function loadReports() {
  try {
    const response = await apiRequest('/api/reports', { method: 'GET' });
    state.reports = Array.isArray(response.reports) ? response.reports : [];
  } catch {
    state.reports = [];
  }
}

async function loadDisciplinaryActions() {
  if (!state.selectedSchoolId) {
    state.disciplinaryActions = [];
    return;
  }

  try {
    const response = await apiRequest(`/api/disciplinary-actions?schoolId=${encodeURIComponent(state.selectedSchoolId)}`, { method: 'GET' });
    state.disciplinaryActions = Array.isArray(response.actions) ? response.actions : [];
  } catch {
    state.disciplinaryActions = [];
  }
}

function loadDraft() {
  try {
    const raw = localStorage.getItem(storageKeys.draft);
    if (!raw) return;

    const draft = JSON.parse(raw);
    state.selectedSchoolId = draft.selectedSchoolId || state.selectedSchoolId;
    state.manualSchoolSelection = Boolean(draft.manualSchoolSelection);
    state.selectedClass = draft.selectedClass || state.selectedClass;
    state.selectedStudents = Array.isArray(draft.selectedStudents) ? draft.selectedStudents : [];
    state.selectedOccurrence = draft.selectedOccurrence || state.selectedOccurrence;
    state.customOccurrence = draft.customOccurrence || '';
    state.notes = draft.notes || '';
    state.dateTime = draft.dateTime || '';
    state.photoDataUrl = draft.photoDataUrl || '';
    state.location = draft.location || null;
    state.historyMode = draft.historyMode || 'selected';
  } catch {
    clearDraft();
  }
}

function saveDraft() {
  localStorage.setItem(storageKeys.draft, JSON.stringify({
    selectedSchoolId: state.selectedSchoolId,
    manualSchoolSelection: state.manualSchoolSelection,
    selectedStudents: state.selectedStudents,
    selectedClass: state.selectedClass,
    selectedOccurrence: state.selectedOccurrence,
    customOccurrence: state.customOccurrence,
    notes: state.notes,
    dateTime: state.dateTime,
    photoDataUrl: state.photoDataUrl,
    location: state.location,
    historyMode: state.historyMode,
  }));
}

function clearDraft() {
  localStorage.removeItem(storageKeys.draft);
  state.manualSchoolSelection = false;
  state.selectedStudents = [];
  state.customOccurrence = '';
  state.notes = '';
  state.dateTime = '';
  state.photoDataUrl = '';
  state.location = null;
  state.historyMode = 'selected';
  rebuildSchoolDependentState();
}

